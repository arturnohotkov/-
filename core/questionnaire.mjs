export function fullSurvey(criteria) {
 return criteria.flatMap((c,component)=>[
  {id:c.id,component,anchor:true,title:c.title,question:c.question,options:c.options,action:c.action},
  ...extras[component].map(([id,title,question,options,action])=>({id,component,anchor:false,title,question,options,action}))
 ]);
}
export function practiceResult(groups) {
 const scores=Object.values(groups).filter(Number.isFinite);
 if (!scores.length) return {score:null,category:'hidden',label:'Недостатньо даних'};
 const score=scores.reduce((sum,x)=>sum+x,0)/scores.length;
 if (scores.length===2 && Math.abs(scores[0]-scores[1])>=20) return {score,category:'split',label:'Розбіжність між групами'};
 if (score>=80) return {score,category:'strong',label:'Сильна практика'};
 if (score>=60) return {score,category:'stable',label:'Стабільна практика'};
 if (score>=40) return {score,category:'forming',label:'Практика формується'};
 return {score,category:'priority',label:'Пріоритет розвитку'};
}
